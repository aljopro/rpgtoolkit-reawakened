/**
 * The RGB triple for palette index `i` (format-spec §3.1). `i` is masked to
 * the low byte so a caller cannot read past the table; indices really are
 * 0…255, with 255 reserved for transparency by the tileset formats.
 */
export function vgaPaletteEntry(index: number): { r: number; g: number; b: number } {
  const at = (index & 0xff) * 3;
  return {
    r: VGA_DEFAULT_PALETTE[at] ?? 0,
    g: VGA_DEFAULT_PALETTE[at + 1] ?? 0,
    b: VGA_DEFAULT_PALETTE[at + 2] ?? 0,
  };
}
