/**
 * The RGB triple for palette index `i` (docs/spec/formats/tiles.md#dos-palette).
 * `i` is masked to the low byte so a caller cannot read past the table; indices
 * really are 0…255, with 255 reserved for transparency by the tileset formats.
 */
export function dosPaletteEntry(index: number): { r: number; g: number; b: number } {
  const at = (index & 0xff) * 3;
  return {
    r: DOS_PALETTE[at] ?? 0,
    g: DOS_PALETTE[at + 1] ?? 0,
    b: DOS_PALETTE[at + 2] ?? 0,
  };
}
